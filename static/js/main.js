// Entry point of the frontend.
//
// serve_index() injects `window.DEFAULT_PATH` through a classic inline script
// and then references this file as `<script type="module">`. Classic scripts
// run before deferred module scripts, so the default path is set by the time
// any module is evaluated.
//
// Two things happen here and nowhere else:
//   1. the startup wiring (DOMContentLoaded)
//   2. the handful of functions that static/index.html and generated markup
//      still call through inline `onclick` — module scope is not global, so
//      they have to be published on `window` explicitly. Everything the app
//      calls internally goes through imports, not through these globals.

import { loadConfigs, saveConfig, deleteConfig, persistConfigs } from './ui/config.js';
import { initFileBrowser } from './ui/browser.js';
import {
    closeMenuPanel,
    handleDocumentClickForMenu,
    handleMenuKeydown,
    loadCurrentUser,
    openMenuPanel,
    performLogout,
    setSectionLoaders,
    showConfigHintIfEmpty,
    showMenuSection,
    toggleMainMenu
} from './ui/menu.js';
import { deleteSyncJob, loadSyncJobs, viewSyncLog } from './ui/jobs.js';
import { previewRenderers } from './ui/preview.js';
// Imported for its side effect: registers previewRenderers.text.
import './ui/preview-text.js';
// Imported for its side effect: registers previewRenderers.image.
import './ui/preview-image.js';
import { loadRemoteFiles, onRemoteSelectChange, selectRemoteFolder } from './ui/remote.js';
import { closeProgressModal, closeSyncModal, startSync } from './ui/sync.js';
import { createTask, deleteTask, loadTasks, openCreateTaskModal, startTaskFromList } from './ui/tasks.js';
import { initSyncMode } from './ui/syncmode.js';
import { initRemotePane } from './ui/remotepane.js';
import { removeToast } from './util/dom.js';

// The panel sections reload themselves when they become visible. Registering
// the loaders here keeps menu.js free of imports from the feature modules.
setSectionLoaders({
    config: loadConfigs,
    sync: loadSyncJobs,
    tasks: loadTasks
});

// Initialize app
document.addEventListener('DOMContentLoaded', function () {
    // Who is signed in. Deliberately first: it is the cheapest request in the
    // startup burst, and if the session is gone it is the one that sends the
    // page to /login before the rest of the UI has drawn anything.
    loadCurrentUser();

    // Load initial data
    loadConfigs().then(() => {
        // Without any remote the user has to start in the configuration section
        showConfigHintIfEmpty();
    });
    // Before the browser: the restored layout decides how wide the file list
    // is, and the first render should already see the final width.
    initSyncMode();
    // After initSyncMode(): the pane registers itself and is mounted right
    // away when the restored mode is already 'sync'.
    initRemotePane();
    initFileBrowser();
    loadSyncJobs();
    loadTasks();

    // Set up form submission
    document.getElementById('config-form').addEventListener('submit', saveConfig);

    // Sign out. Bound here instead of as an inline `onclick`, so the menu entry
    // keeps working as a plain `<a href="/logout">` if this script never runs.
    const logoutLink = document.getElementById('menu-logout');
    if (logoutLink) {
        logoutLink.addEventListener('click', performLogout);
    }

    // Global keyboard handling for the menu (ESC) and focus trap inside the panel
    document.addEventListener('keydown', handleMenuKeydown);

    // Close the dropdown when clicking anywhere outside of it
    document.addEventListener('click', handleDocumentClickForMenu);

    // Auto-refresh sync jobs
    setInterval(loadSyncJobs, 2000);
});

// Called from inline handlers in static/index.html
Object.assign(window, {
    toggleMainMenu,
    openMenuPanel,
    closeMenuPanel,
    showMenuSection,
    persistConfigs,
    onRemoteSelectChange,
    openCreateTaskModal,
    startSync,
    createTask
});

// No inline handler references these today, but they were part of the global
// surface before the split and the modals are closed from markup in places
// that are easy to add to. Kept published so nothing breaks silently.
Object.assign(window, { closeSyncModal, closeProgressModal });

// Called from inline handlers in markup that is generated by JS
Object.assign(window, {
    deleteConfig,
    loadRemoteFiles,
    selectRemoteFolder,
    viewSyncLog,
    deleteSyncJob,
    startTaskFromList,
    deleteTask,
    removeToast
});

// Extension point for the preview renderers of the follow-up tickets. Modules
// should import it from ./ui/preview.js; the global stays for parity with the
// documented `previewRenderers.image = …` snippet.
window.previewRenderers = previewRenderers;
